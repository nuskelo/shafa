@dataclass(frozen=True)
class Target:
    """Лист Клубку: звичайний і (якщо є) зимовий; `always_winter` — лише зимовий (валянки)."""

    leaf: int
    winter: int | None = None
    always_winter: bool = False

    def pick(self, winter: bool) -> int:
        if self.winter is None:
            return self.leaf
        return self.winter if winter or self.always_winter else self.leaf


def _table(rows: list[tuple[tuple[str, ...], Target]]) -> dict[str, Target]:
    return {_key(name): target for names, target in rows for name in names}


def _key(value: str) -> str:
    return value.strip().casefold().replace("’", "'").replace("ʼ", "'")


