def _in_group(path: str, group: str) -> bool:
    return _key(path).startswith(_key(group) + " /")


def leaf_id(path: str, winter: bool, gender: str | None = None, title: str = "") -> int | None:
    """Лист Клубку для розділу Картки (`Жіночий одяг / Взуття / Черевики`) або None.

    `winter` — у сезоні Картки є «Зима»; `gender` — поле «Стать» Картки (лише для сумок і гаманців:
    «Для чоловіків» → чоловічі листки); `title` — назва Картки («маленьк…» → клатчі).
    """
    path = shafa_catalog.normalize_section(path)
    name = path.rsplit(SEP, 1)[-1]
    key = _key(name)
    for group, table in ((WOMEN, _WOMEN), (MEN, _MEN), *((g, _KIDS) for g in KIDS)):
        if _in_group(path, group):
            target = table.get(key)
            return target.pick(winter) if target else None
    is_bag = _in_group(path, BAGS)
    is_wallet = _in_group(path, WALLETS)
    if not (is_bag or is_wallet):
        return None
    man = _key(gender or "") == MAN
    if is_wallet:
        if key not in _WALLETS:
            return None
        return MEN_WALLET if man else _WALLETS[key].leaf
    if key in MEN_ONLY_BAGS:
        return MEN_BAG
    target = _BAGS.get(key)
    if target is None:
        return None
    if man:
        return MEN_BAG
    if key == _key("Сумки") and "маленьк" in title.casefold():
        return SMALL_BAG
    return target.leaf


def all_leaf_ids() -> list[int]:
    return sorted(EXPECTED)
