_NUMBER = re.compile(r"[\d.,]+( см)?")  # довжина устілки: «25,5 см», «22,5» — без слів


def _norm(text: str) -> str:
    text = text.replace("ё", "е").replace("Ё", "Е")
    for mark in "’ʼ`´":  # апостроф у Шафи буває різний
        text = text.replace(mark, "'")
    return " ".join(text.split()).casefold()


_SAME = {_norm(name) for name in SAME}
_INDEX: dict[str, int] = {}
for _i, _group in enumerate(GROUPS):
    for _name in _group:
        _INDEX.setdefault(_norm(_name), _i)  # одне написання — одна назва (це перевіряє тест)


def variants(text: str) -> list[str]:
    """Усі написання назви (спершу те, що передали). Немає в таблиці — лише вона сама."""
    index = _INDEX.get(_norm(text))
    if index is None:
        return [text]
    return [text] + [v for v in GROUPS[index] if _norm(v) != _norm(text)]


def key(text: str) -> str:
    """Ключ порівняння: однаковий для всіх написань однієї назви; для невідомих — сам текст."""
    index = _INDEX.get(_norm(text))
    return f"#{index}" if index is not None else _norm(text)


def equivalent(a: str, b: str) -> bool:
    return key(a) == key(b)


def keys(texts: Iterable[str]) -> list[str]:
    return sorted(key(t) for t in texts)


def covered(text: str) -> bool:
    """Назву знає таблиця: є група, явно «однакова обома мовами» чи це число (тест-охоронець)."""
    return _norm(text) in _INDEX or _norm(text) in _SAME or bool(_NUMBER.fullmatch(text.strip()))
