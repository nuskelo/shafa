def stop(site: str, code: str | None) -> Hint | None:
    table = KLUBOK_STOPS if site == "klubok" else STOPS
    return table.get(code or "")


def problem(code: str | None, site: str = "shafa") -> Hint | None:
    code = code or ""
    if site == "klubok":
        return KLUBOK_PROBLEMS.get(code)
    return PROBLEMS.get(code) or (ROBOT_PROBLEM if code.startswith("robot_") else None)
