"""BOT-019: один довідник «що сталось → що робити» для кожної зупинки, Проблеми й події.

Екран (Проблеми, панель робота, «Сесії»), бот (⛔ зупинка, ⚠️ нова Проблема, події) і денний звіт
беруть тексти звідси — окремих копій немає. Назви кнопок — рівно як у програмі.

Ключі: `STOPS` / `KLUBOK_STOPS` — `sessions.stop_code`; `PROBLEMS` — `items.problem_code` Шафи;
`KLUBOK_PROBLEMS` — Проблеми Клубку; `EVENTS` — гучні події журналу (`events.py`) і ШІ.
Модуль нічого не імпортує з програми: його читають і `web`, і `bot`, і `robot`.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class Hint:
    title: str  # коротка назва: мітка в рядку Проблеми, у звіті, у заголовку підказки
    what: str  # що сталось — один рядок
    do: tuple[str, ...] = ()  # що робити: 1–3 кроки, з точними назвами кнопок програми
    loud: bool = False  # гучне повідомлення Вікторії/Власнику, а не рядок у тихій збірці


def steps(hint: Hint) -> str:
    """«1) …; 2) …» — один крок без номера."""
    if len(hint.do) == 1:
        return hint.do[0]
    return "; ".join(f"{n}) {step}" for n, step in enumerate(hint.do, 1))


def inline(hint: Hint) -> str:
    """«що сталось — що робити» одним рядком (панель, «Сесії»). Довга інструкція (3+ кроки) тут —
    лише перший крок; повна — в боті й на панелі окремим блоком."""
    if not hint.do:
        return hint.what
    return f"{hint.what} — {'; '.join(hint.do if len(hint.do) <= 2 else hint.do[:1])}"


def advice(hint: Hint) -> str:
    """«Що робити: 1) …; 2) …» — рядок підказки для бота; порожньо, коли робити нічого."""
    return f"Що робити: {steps(hint)}." if hint.do else ""


def card_text(hint: Hint) -> str:
    """Довгий текст на Картці-Проблемі: що сталось і що робити."""
    return f"{hint.what}. {advice(hint)}" if hint.do else f"{hint.what}."


